import { expect, test } from '@playwright/test'
import { addLine, apiJson, chooseProfile, finishPages, login, nextStep, toPages, recordAndSend, uniqueName, PARENT_NAME } from './helpers'

test.describe.configure({ mode: 'serial' })

test.describe('single voice book', () => {
    test('a relative creates and records a solo book that goes to review', async ({ page }, info) => {
        const project = info.project.name
        const mamie = uniqueName('Mamie', project)
        await login(page)
        await chooseProfile(page, mamie)
        await expect(page).toHaveURL(/\/home/)
        await page.getByRole('link', { name: 'Proposer un livre' }).click()
        await expect(page.getByRole('heading', { name: 'Le livre' })).toBeVisible()
        await expect(page.getByText('1/3')).toBeVisible()
        await expect(page.getByRole('button', { name: 'Une seule voix' })).toHaveAttribute('aria-pressed', 'true')
        await page.getByLabel('Titre du livre').fill(`Le caméléon ${project}`)
        await toPages(page)
        await expect(page.getByRole('heading', { name: 'Les pages' })).toBeVisible()
        await expect(page.getByText('Qui parle ?')).toHaveCount(0)
        await addLine(page, 1, null, 'Il était une fois un caméléon timide.')
        await addLine(page, 1, null, 'Il changeait de couleur quand on le regardait.')
        await finishPages(page)
        await expect(page.getByRole('heading', { name: 'Vérifier' })).toBeVisible()
        await page.getByRole('button', { name: 'Passer au studio' }).click()
        await expect(page).toHaveURL(/\/studio/)
        await recordAndSend(page)
        await expect(page.getByText('1/2').first()).toBeVisible()
        await recordAndSend(page)
        await expect(page.getByRole('button', { name: 'Publier le livre' })).toHaveCount(0)
        await expect(page.getByRole('button', { name: 'Aucune prise à envoyer' })).toBeVisible()
        const books = await apiJson<{ kind: string; status: string; title: string }[]>(page, '/books')
        const solo = books.find(book => book.title === `Le caméléon ${project}`)
        expect(solo?.kind).toBe('solo')
        expect(solo?.status).toBe('in_review')
    })

    test('a parent can start a solo book for a chosen reader', async ({ page }, info) => {
        const mamie = uniqueName('Mamie', info.project.name)
        await login(page)
        await chooseProfile(page, PARENT_NAME)
        await page.goto('/books/new')
        await page.getByRole('button', { name: 'Une seule voix' }).click()
        await page.getByLabel('Titre du livre').fill(`Une voix ${info.project.name}`)
        await expect(page.getByText('1/3')).toBeVisible()
        await nextStep(page)
        await page.getByRole('button', { name: mamie }).click()
        await toPages(page)
        await addLine(page, 1, null, 'Une seule voix.')
        await finishPages(page)
        await expect(page.getByText(`${mamie} lit tout le livre`)).toBeVisible()
        await page.getByRole('button', { name: 'Retour' }).click()
        await expect(page.getByRole('heading', { name: 'Les pages' })).toBeVisible()
    })
})
